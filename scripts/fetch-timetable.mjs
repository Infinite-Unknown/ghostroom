// One-off: fetch APU's public week timetable, strip personal fields, dedupe, keep 2 blocks (60 rooms).
// Writes data/timetable-snapshot.json (readable) and apps-script/Timetable.gs (compact, paste into Apps Script).
// Run: node scripts/fetch-timetable.mjs
import { writeFileSync, mkdirSync } from 'node:fs';

const URL = 'https://s3-ap-southeast-1.amazonaws.com/open-ws/weektimetable';
const BLOCKS = ['B', 'D'];   // the two busiest teaching blocks in the feed
const ROOMS_PER_BLOCK = 30;  // ponytail: busiest 30 per block = 60 rows, the rooms_live cap

const feed = await (await fetch(URL)).json(); // data only: we read fields, never eval anything
if (!Array.isArray(feed)) throw new Error('feed is not an array');

// One session per room + date + time. Per-intake duplicates collapse here; LECTID/NAME/SAMACCOUNTNAME never leave this loop.
const byKey = new Map();
for (const r of feed) {
  const room = String(r.ROOM || '');
  const m = room.match(/^([A-Z])-(\d\d)-(\d\d)$/);
  if (!m || !BLOCKS.includes(m[1])) continue;
  const date = String(r.DATESTAMP_ISO).slice(0, 10);
  const from = String(r.TIME_FROM_ISO).slice(11, 16);
  const to = String(r.TIME_TO_ISO).slice(11, 16);
  if (!/^\d{4}-\d\d-\d\d$/.test(date) || !/^\d\d:\d\d$/.test(from) || !/^\d\d:\d\d$/.test(to)) continue;
  const key = [room, date, from, to].join('|');
  const s = byKey.get(key) || { room, date, from, to, modules: new Set() };
  s.modules.add(String(r.MODULE_NAME || '').trim());
  byKey.set(key, s);
}
const all = [...byKey.values()];

// Keep the busiest rooms per block so the grid has real traffic.
const count = {};
for (const s of all) count[s.room] = (count[s.room] || 0) + 1;
const rooms = BLOCKS.flatMap(b =>
  Object.keys(count).filter(r => r[0] === b).sort((x, y) => count[y] - count[x] || x.localeCompare(y)).slice(0, ROOMS_PER_BLOCK)
).sort();
const keep = new Set(rooms);

const sessions = all.filter(s => keep.has(s.room))
  .map(s => ({ room: s.room, date: s.date, from: s.from, to: s.to, module: [...s.modules].sort()[0] }))
  .sort((a, b) => (a.date + a.from + a.room).localeCompare(b.date + b.from + b.room));
const dates = [...new Set(sessions.map(s => s.date))].sort();

const snapshot = { source: URL, fetched_at: new Date().toISOString(), blocks: BLOCKS, rooms, dates: [dates[0], dates.at(-1)], sessions };
mkdirSync('data', { recursive: true });
writeFileSync('data/timetable-snapshot.json', JSON.stringify(snapshot, null, 1));

// Compact copy for Apps Script: rooms + module names as lists, each session = [roomIdx, fromMin, toMin, moduleIdx] per date
// (minutes after local midnight, MYT).
const mins = hhmm => Number(hhmm.slice(0, 2)) * 60 + Number(hhmm.slice(3));
const modules = [...new Set(sessions.map(s => s.module))].sort();
const days = {};
for (const s of sessions) (days[s.date] ||= []).push([rooms.indexOf(s.room), mins(s.from), mins(s.to), modules.indexOf(s.module)]);
const gs = `// GENERATED by scripts/fetch-timetable.mjs on ${snapshot.fetched_at}. Do not edit by hand; re-run the script.
// Real APU timetable (public feed), blocks ${BLOCKS.join('+')}, lecturer fields removed. Session = [roomIdx, fromMin, toMin, moduleIdx], minutes after midnight MYT.
var TIMETABLE = ${JSON.stringify({ fetched_at: snapshot.fetched_at, rooms, modules, days })};
`;
mkdirSync('apps-script', { recursive: true });
writeFileSync('apps-script/Timetable.gs', gs);

console.log(`${feed.length} feed rows -> ${sessions.length} sessions, ${rooms.length} rooms, ${dates[0]}..${dates.at(-1)}, Timetable.gs ${(gs.length / 1024).toFixed(0)} KB`);
